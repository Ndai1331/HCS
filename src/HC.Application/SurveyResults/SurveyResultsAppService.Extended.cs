namespace HC.SurveyResults;

public class SurveyResultsAppService : SurveyResultsAppServiceBase, ISurveyResultsAppService
{
    //<suite-custom-code-autogenerated>
    protected ISurveyResultRepository _surveyResultRepository;
    protected SurveyResultManager _surveyResultManager; 
    protected IRepository<HC.SurveyCriterias.SurveyCriteria, Guid> _surveyCriteriaRepository;
    protected IRepository<HC.SurveySessions.SurveySession, Guid> _surveySessionRepository;

    public SurveyResultsAppService(ISurveyResultRepository surveyResultRepository, SurveyResultManager surveyResultManager, IDistributedCache<SurveyResultDownloadTokenCacheItem, string> downloadTokenCache, IRepository<HC.SurveyCriterias.SurveyCriteria, Guid> surveyCriteriaRepository, IRepository<HC.SurveySessions.SurveySession, Guid> surveySessionRepository) : base(surveyResultRepository, surveyResultManager, downloadTokenCache, surveyCriteriaRepository, surveySessionRepository)
    {
        _surveyResultRepository = surveyResultRepository;
        _surveyResultManager = surveyResultManager;
        _surveyCriteriaRepository = surveyCriteriaRepository;
        _surveySessionRepository = surveySessionRepository;
    }
    //</suite-custom-code-autogenerated>
    
    /// <summary>
    /// Public API to create survey result without authentication
    /// </summary>
    [AllowAnonymous]
    public virtual async Task<SurveyResultDto> CreatePublicSurveyResultAsync(SurveyResultCreateDto input)
    {
        var surveyResult = await _surveyResultManager.CreateAsync(
            input.SurveySessionId,
            input.SurveyCriteriaId,
            input.Rating
        );

        await _surveyResultRepository.InsertAsync(surveyResult);
        return ObjectMapper.Map<SurveyResult, SurveyResultDto>(surveyResult);
    }
}