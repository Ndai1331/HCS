    /// <summary>
    /// Public API to create survey result without authentication
    /// </summary>
    [AllowAnonymous]
    public virtual async Task<SurveyResultDto> CreatePublicSurveyResultAsync(SurveyResultCreateDto input)
    {
        try 
        {   

            var surveyCriteria = await _surveyCriteriaRepository.GetAsync(x=> x.Id == input.SurveyCriteriaId);
            var tenantId = surveyCriteria?.TenantId;
            using (CurrentTenant.Change(tenantId))
            {
                //check if survey result already exists
                var surveyResult = await _surveyResultRepository.GetAsync(x=> x.SurveyCriteriaId == input.SurveyCriteriaId && x.SurveySessionId == input.SurveySessionId);
                if (surveyResult != null)
                {
                    //update survey result
                    surveyResult = await _surveyResultManager.UpdateAsync(surveyResult.Id, input.SurveyCriteriaId, input.SurveySessionId, input.Rating);
                }
                else
                {
                    //create survey result
                    surveyResult = await _surveyResultManager.CreateAsync(input.SurveyCriteriaId, input.SurveySessionId, input.Rating);
                }
                return ObjectMapper.Map<SurveyResult, SurveyResultDto>(surveyResult);
            }
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, $"Error creating survey result for session {input.SurveySessionId} and criteria {input.SurveyCriteriaId}");
            throw new UserFriendlyException(ex.Message);
        }
    }

    [AllowAnonymous]
    public virtual async Task<List<SurveyResultDto>> CreatePublicSurveyResultsAsync(List<SurveyResultCreateDto> input)
    {
        try 
        {   
            var surveyResults = new List<SurveyResultDto>();
            var firstCriteriaId = input.FirstOrDefault(x=> x.SurveyCriteriaId != default)?.SurveyCriteriaId;
            var surveyCriteria = await _surveyCriteriaRepository.FirstOrDefaultAsync(x=> x.Id == firstCriteriaId);
            var tenantId = surveyCriteria != null ? surveyCriteria.TenantId : null;

            _logger.LogInformation($"Input survey results: {JsonSerializer.Serialize(input)}");
            using (CurrentTenant.Change(tenantId))
            {
                _logger.LogInformation($"Changing tenant to: {tenantId}");
                //check if survey result already exists
                foreach (var surveyResultCreateDto in input)
                {
                    var surveyResult = await _surveyResultRepository.FirstOrDefaultAsync(x=> 
                    x.SurveyCriteriaId == surveyResultCreateDto.SurveyCriteriaId 
                    && x.SurveySessionId == surveyResultCreateDto.SurveySessionId);

                    _logger.LogInformation($"Survey result: {JsonSerializer.Serialize(surveyResult)}");
                    if (surveyResult != null)
                    {
                        _logger.LogInformation($"Updating survey result: {JsonSerializer.Serialize(surveyResult)}");
                        surveyResult = await _surveyResultManager.UpdateAsync(surveyResult.Id, surveyResultCreateDto.SurveyCriteriaId, surveyResultCreateDto.SurveySessionId, surveyResultCreateDto.Rating);
                    }
                    else
                    {
                        _logger.LogInformation($"Creating survey result: {JsonSerializer.Serialize(surveyResultCreateDto)}");
                        surveyResult = await _surveyResultManager.CreateAsync(
                            surveyResultCreateDto.SurveyCriteriaId, 
                            surveyResultCreateDto.SurveySessionId, 
                            surveyResultCreateDto.Rating);
                    }
                    _logger.LogInformation($"Survey result added: {JsonSerializer.Serialize(surveyResult)}");
                    surveyResults.Add(ObjectMapper.Map<SurveyResult, SurveyResultDto>(surveyResult));
                    _logger.LogInformation($"Survey results: {JsonSerializer.Serialize(surveyResults)}");
                }
            }
            _logger.LogInformation($"Survey results: {JsonSerializer.Serialize(surveyResults)}");
            return surveyResults;
        }
        catch (Exception ex)
        {
            throw new UserFriendlyException(ex.Message);
        }
    }

    public virtual async Task<PagedResultDto<SurveyResultSessionSummaryDto>> GetSessionSummaryListAsync(GetSurveyResultSessionSummariesInput input)
    {
        var resultQueryable = await _surveyResultRepository.GetQueryableAsync();
        var sessionQueryable = await _surveySessionRepository.GetQueryableAsync();

        var query =
            from session in sessionQueryable
            join result in resultQueryable on session.Id equals result.SurveySessionId
            where !input.SurveyLocationId.HasValue || session.SurveyLocationId == input.SurveyLocationId.Value
            group result by new
            {
                session.Id,
                session.FullName,
                session.PhoneNumber,
                session.PatientCode,
                session.Note,
                session.SurveyTime
            }
            into grouped
            select new SurveyResultSessionSummaryDto
            {
                SurveySessionId = grouped.Key.Id,
                AverageRating = grouped.Average(x => (double)x.Rating),
                FullName = grouped.Key.FullName,
                PhoneNumber = grouped.Key.PhoneNumber,
                PatientCode = grouped.Key.PatientCode,
                Note = grouped.Key.Note,
                SurveyTime = grouped.Key.SurveyTime
            };

        var sorting = string.IsNullOrWhiteSpace(input.Sorting) ? "SurveyTime desc" : input.Sorting;
        var totalCount = await AsyncExecuter.LongCountAsync(query);
        var items = await AsyncExecuter.ToListAsync(
            query.OrderBy(sorting)
                .PageBy(input.SkipCount, input.MaxResultCount)
        );

        foreach (var item in items)
        {
            item.AverageRating = Math.Round(item.AverageRating, 2);
        }

        return new PagedResultDto<SurveyResultSessionSummaryDto>
        {
            TotalCount = totalCount,
            Items = items
        };
    }

    public virtual async Task<List<SurveyResultSessionDetailDto>> GetSessionDetailListAsync(GetSurveyResultSessionDetailsInput input)
    {
        var resultQueryable = await _surveyResultRepository.GetQueryableAsync();
        var sessionQueryable = await _surveySessionRepository.GetQueryableAsync();
        var criteriaQueryable = await _surveyCriteriaRepository.GetQueryableAsync();

        var query =
            from result in resultQueryable
            join session in sessionQueryable on result.SurveySessionId equals session.Id
            join criteria in criteriaQueryable on result.SurveyCriteriaId equals criteria.Id
            where result.SurveySessionId == input.SurveySessionId
            where !input.SurveyLocationId.HasValue || session.SurveyLocationId == input.SurveyLocationId.Value
            orderby criteria.Name
            select new SurveyResultSessionDetailDto
            {
                SurveyResultId = result.Id,
                SurveySessionId = session.Id,
                SurveyCriteriaId = criteria.Id,
                SurveyCriteriaName = criteria.Name,
                Rating = result.Rating,
                FullName = session.FullName,
                PhoneNumber = session.PhoneNumber,
                PatientCode = session.PatientCode,
                Note = session.Note,
                SurveyTime = session.SurveyTime
            };

        return await AsyncExecuter.ToListAsync(query);
    }

    public virtual async Task<SurveyResultStatisticsDto> GetStatisticsByLocationAsync(Guid? surveyLocationId)
    {
        var statistics = new SurveyResultStatisticsDto();

        try
        {
            _logger.LogInformation($"GetStatisticsByLocationAsync Getting survey result statistics for location {surveyLocationId}");
            var queryable = await _surveyResultRepository.GetQueryableAsync();
            var sessionQueryable = await _surveySessionRepository.GetQueryableAsync();
            var criteriaQueryable = await _surveyCriteriaRepository.GetQueryableAsync();

            // Join SurveyResults with SurveySessions
            var query = from result in queryable
                       join session in sessionQueryable on result.SurveySessionId equals session.Id
                       join criteria in criteriaQueryable on result.SurveyCriteriaId equals criteria.Id
                       where !surveyLocationId.HasValue || session.SurveyLocationId == surveyLocationId.Value
                       select new
                       {
                           result.Rating,
                           criteria.Name,
                           criteria.Code
                       };
            _logger.LogInformation($"GetStatisticsByLocationAsync Query: {JsonSerializer.Serialize(query)}");
            var data = await AsyncExecuter.ToListAsync(query);

            _logger.LogInformation($"GetStatisticsByLocationAsync Data: {JsonSerializer.Serialize(data)}");
            // Calculate rating distribution
            statistics.RatingDistribution = data
                .GroupBy(x => x.Rating)
                .ToDictionary(g => g.Key, g => g.Count());

            _logger.LogInformation($"GetStatisticsByLocationAsync Rating Distribution: {JsonSerializer.Serialize(statistics.RatingDistribution)}");

            // Ensure all ratings 0-5 are present
            for (int i = 0; i <= 5; i++)
            {
                if (!statistics.RatingDistribution.ContainsKey(i))
                {
                    statistics.RatingDistribution[i] = 0;
                }
            }
            _logger.LogInformation($"GetStatisticsByLocationAsync Rating Distribution: {JsonSerializer.Serialize(statistics.RatingDistribution)}");
            // Calculate criteria average ratings
            statistics.CriteriaAverageRatings = data
                .GroupBy(x => x.Name)
                .Select(g => new
                {
                    CriteriaName = g.Key,
                    AverageRating = g.Average(x => x.Rating)
                })
                .OrderBy(x => x.CriteriaName)
                .ToDictionary(x => x.CriteriaName, x => Math.Round(x.AverageRating, 1));
            _logger.LogInformation($"GetStatisticsByLocationAsync Criteria Average Ratings: {JsonSerializer.Serialize(statistics.CriteriaAverageRatings)}");
            return statistics;
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Error getting survey result statistics");
            return statistics;
        }
    }
