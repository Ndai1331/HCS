    public SurveyLocationsAppService(ISurveyLocationRepository surveyLocationRepository, SurveyLocationManager surveyLocationManager, IDistributedCache<SurveyLocationDownloadTokenCacheItem, string> downloadTokenCache) : base(surveyLocationRepository, surveyLocationManager, downloadTokenCache)
    {
    }
