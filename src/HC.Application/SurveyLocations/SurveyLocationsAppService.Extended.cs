    /// <summary>
    /// Public API to get survey location by id without authentication
    /// </summary>
    [AllowAnonymous]
    public virtual async Task<SurveyLocationDto> GetPublicSurveyLocationAsync(Guid id)
    {
        var surveyLocation = await _surveyLocationRepository.GetAsync(x => x.Id == id);
        return ObjectMapper.Map<SurveyLocation, SurveyLocationDto>(surveyLocation);
    }
}