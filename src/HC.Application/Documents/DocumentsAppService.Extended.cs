    /// <summary>
    /// Inbox document IDs: non-workflow VIEW assignments to current user, plus explicit SentToMe rows (user or department).
    /// </summary>
    private async Task<List<Guid>> GetSentToMeDocumentIdsAsync(Guid userId)
    {
        var assignmentQ = await _documentAssignmentRepository.GetQueryableAsync();
        var docQ = await _documentRepository.GetQueryableAsync();
        var viewAction = DocumentAssignmentActionType.VIEW.ToString();

        var fromAssignmentsQuery = assignmentQ
            .Where(a => a.ReceiverUserId == userId
                        && a.ActionType == viewAction
                        && a.WorkflowStepTemplateId == null)
            .Join(docQ.Where(d => d.SourceType != DocumentSourceType.Workflow),
                a => a.DocumentId,
                d => d.Id,
                (_, d) => d.Id)
            .Distinct();

        var fromAssignments = await AsyncExecuter.ToListAsync(fromAssignmentsQuery);

        var userDepts = await _userDepartmentRepository.GetListAsync(ud => ud.UserId == userId && ud.IsActive);
        var deptIds = userDepts.Select(ud => ud.DepartmentId).Distinct().ToList();

        IQueryable<Guid> explicitQuery = docQ
            .Where(d => d.SourceType == DocumentSourceType.SentToMe
                        && (d.ReceiverUserId == userId
                            || (d.DepartmentId != null && deptIds.Contains(d.DepartmentId.Value))))
            .Select(d => d.Id);

        var fromExplicit = await AsyncExecuter.ToListAsync(explicitQuery);

        return fromAssignments.Union(fromExplicit).Distinct().ToList();
    }

    /// <summary>
    /// Prefer Name + Surname (full name); fall back to UserName / Email.
    /// </summary>
    private static string GetIdentityUserFullDisplayName(IdentityUser user)
    {
        var parts = new[] { user.Surname, user.Name }.Where(s => !string.IsNullOrWhiteSpace(s));
        var full = string.Join(' ', parts).Trim();
        return string.IsNullOrWhiteSpace(full)
            ? (user.UserName ?? user.Email ?? user.Id.ToString())
            : full;
    }

    private async Task PopulateSentToMeDisplayNamesAsync(List<DocumentWithNavigationPropertiesDto> dtos)
    {
        if (dtos.Count == 0)
        {
            return;
        }

        var userIds = dtos
            .Select(d => d.Document.FromUserId)
            .Where(id => id.HasValue)
            .Select(id => id!.Value)
            .Distinct()
            .ToList();

        List<IdentityUser> users;
        if (userIds.Count > 0)
        {
            var userQ = (await _identityUserRepository.GetQueryableAsync()).Where(u => userIds.Contains(u.Id));
            users = await AsyncExecuter.ToListAsync(userQ);
        }
        else
        {
            users = new List<IdentityUser>();
        }

        var userDict = users.ToDictionary(u => u.Id, GetIdentityUserFullDisplayName);

        var deptIds = dtos
            .Select(d => d.Document.DepartmentId)
            .Where(id => id.HasValue)
            .Select(id => id!.Value)
            .Distinct()
            .ToList();

        var depts = deptIds.Count > 0
            ? await _departmentRepository.GetListAsync(d => deptIds.Contains(d.Id))
            : new List<Department>();

        var deptDict = depts.ToDictionary(d => d.Id, d => d.Name ?? d.Id.ToString());

        foreach (var dto in dtos)
        {
            if (dto.Document.FromUserId.HasValue && userDict.TryGetValue(dto.Document.FromUserId.Value, out var fn))
            {
                dto.FromUserDisplayName = fn;
            }

            if (dto.Document.DepartmentId.HasValue && deptDict.TryGetValue(dto.Document.DepartmentId.Value, out var dn))
            {
                dto.DepartmentDisplayName = dn;
            }
        }
    }

    public async Task<bool> SendDocumentAsync(SendDocumentInput input)
    {
        try
        {
            _logger.LogInformation("SendDocumentAsync started: DocumentId={DocumentId}, Recipients={RecipientCount}, Departments={DepartmentCount}",
                input.DocumentId,
                input.Recipients?.Count ?? 0,
                input.Departments?.Count ?? 0);

            // Validate input
            if (input.DocumentId == Guid.Empty)
            {
                throw new UserFriendlyException(L["DocumentId is required"]);
            }

            if ((input.Recipients == null || input.Recipients.Count == 0) &&
                (input.Departments == null || input.Departments.Count == 0))
            {
                throw new UserFriendlyException(L["At least one recipient or department is required"]);
            }

            // Get current user
            var currentUserId = CurrentUser.Id;
            if (currentUserId == null)
            {
                throw new UserFriendlyException(L["User not authenticated"]);
            }

            // Get document info
            var document = await _documentRepository.GetAsync(input.DocumentId);

            var allReceiverUserIds = new List<Guid>();

            // Handle individual recipients
            if (input.Recipients != null && input.Recipients.Count > 0)
            {
                allReceiverUserIds.AddRange(input.Recipients);
            }

            // Handle department recipients
            if (input.Departments != null && input.Departments.Count > 0)
            {
                foreach (var departmentId in input.Departments)
                {
                    // Get all users in the department
                    var userDepartments = await _userDepartmentRepository.GetListAsync(ud => ud.DepartmentId == departmentId && ud.IsActive);
                    var departmentUserIds = userDepartments.Select(ud => ud.UserId).ToList();
                    allReceiverUserIds.AddRange(departmentUserIds);
                }
            }

            // Remove duplicates
            allReceiverUserIds = allReceiverUserIds.Distinct().ToList();

            if (allReceiverUserIds.Count == 0)
            {
                throw new UserFriendlyException(L["No valid recipients found"]);
            }

            _logger.LogInformation("Sending document to {RecipientCount} recipients", allReceiverUserIds.Count);

            // Create notification (ICurrentUser has Name / UserName; no Surname on interface)
            var userFullName = !string.IsNullOrWhiteSpace(CurrentUser.Name)
                ? CurrentUser.Name!
                : (CurrentUser.UserName ?? L["System"]);
            var notificationTitleKey = "DocumentReceived";
            var notificationContentKey = $"DocumentReceivedMessage|{document.StorageNumber}|{document.Title}|{userFullName ?? L["System"]}";

            var notification = new Notification(
                GuidGenerator.Create(),
                notificationTitleKey,
                notificationContentKey,
                SourceType.DOCUMENT.ToString(),
                EventType.DOCUMENT_SENT.ToString(),
                RelatedType.DOCUMENT.ToString(),
                "NORMAL",
                document.Id.ToString()
            );

            notification.TenantId = CurrentTenant.Id;
            await _notificationRepository.InsertAsync(notification);

            var now = Clock.Now; // ISSUE-18 FIX: Use ABP Clock instead of DateTime.Now

            // Create notification receivers and document histories for each user
            foreach (var receiverUserId in allReceiverUserIds)
            {
                // Create notification receiver
                var notificationReceiver = new NotificationReceiver(
                    GuidGenerator.Create(),
                    notification.Id,
                    receiverUserId,
                    false
                );
                notificationReceiver.TenantId = CurrentTenant.Id;
                await _notificationReceiverRepository.InsertAsync(notificationReceiver);

                // Create document history with Action = TRINH
                var documentHistory = await _documentHistoryManager.CreateAsync(
                    input.DocumentId,
                    currentUserId,
                    receiverUserId,
                    nameof(DocumentHistoryAction.TRINH),
                    $"Document sent from user {CurrentUser.UserName ?? L["System"]}"
                );

                // Check if DocumentAssignment already exists for this document and user
                var existingAssignments = await _documentAssignmentRepository.GetListAsync(
                    documentId: input.DocumentId,
                    receiverUserId: receiverUserId
                );

                var existingAssignment = existingAssignments.FirstOrDefault();

                if (existingAssignment != null)
                {
                    // DocumentAssignment exists → Update status to DONE and ProcessedAt
                    existingAssignment.Status = DocumentAssignmentStatus.DONE.ToString();
                    existingAssignment.ProcessedAt = now;
                    existingAssignment.IsCurrent = true;
                    await _documentAssignmentRepository.UpdateAsync(existingAssignment);
                    
                    _logger.LogInformation("Updated existing DocumentAssignment: DocumentId={DocumentId}, ReceiverUserId={ReceiverUserId}",
                        input.DocumentId, receiverUserId);
                }
                else
                {
                    // DocumentAssignment doesn't exist → Create new with status DONE
                    var documentAssignment = await _documentAssignmentManager.CreateAsync(
                        input.DocumentId,
                        null,
                        receiverUserId,
                        (int)DocumentAssignmentStepOrder.ORIGINAL, // ORIGINAL
                        DocumentAssignmentActionType.VIEW.ToString(), // VIEW
                        DocumentAssignmentStatus.DONE.ToString(),
                        now, // AssignedAt
                        now, // ProcessedAt
                        true // IsCurrent
                    );
                    
                    _logger.LogInformation("Created new DocumentAssignment: DocumentId={DocumentId}, ReceiverUserId={ReceiverUserId}",
                        input.DocumentId, receiverUserId);
                }
            }

            // Publish event to RabbitMQ for real-time notification
            await _distributedEventBus.PublishAsync(
                new NotificationCreatedEto
                {
                    NotificationId = notification.Id,
                    ReceiverUserIds = allReceiverUserIds
                }
            );

            _logger.LogInformation("SendDocumentAsync completed successfully: DocumentId={DocumentId}, SentTo={RecipientCount} users",
                input.DocumentId, allReceiverUserIds.Count);

            // Denormalized routing metadata for SentToMe grid (From / Receiver / Department)
            document.FromUserId = currentUserId.Value;
            if (input.Recipients?.Count == 1 && (input.Departments == null || input.Departments.Count == 0))
            {
                document.ReceiverUserId = input.Recipients[0];
                document.DepartmentId = null;
            }
            else if (input.Departments?.Count == 1 && (input.Recipients == null || input.Recipients.Count == 0))
            {
                document.DepartmentId = input.Departments[0];
                document.ReceiverUserId = null;
            }
            else
            {
                document.ReceiverUserId = null;
                document.DepartmentId = null;
            }

            await _documentRepository.UpdateAsync(document);

            // Update document status to DA_GUI (Đã gửi) after successfully sending
            await UpdateDocumentStatusAsync(input.DocumentId, DocumentStatusCode.DA_GUI);

            return true;
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Error in SendDocumentAsync: DocumentId={DocumentId}", input.DocumentId);
            throw;
        }
    }

    public async Task<bool> RevokeDocumentAsync(RevokeDocumentInput input)
    {
        try
        {
            _logger.LogInformation("RevokeDocumentAsync started: DocumentId={DocumentId}", input.DocumentId);

            // Validate input
            if (input.DocumentId == Guid.Empty)
            {
                throw new UserFriendlyException(L["DocumentId is required"]);
            }

            // Get current user
            var currentUserId = CurrentUser.Id;
            if (currentUserId == null)
            {
                throw new UserFriendlyException(L["User not authenticated"]);
            }

            // Get document info
            var document = await _documentRepository.GetAsync(input.DocumentId);
            EnsureArchiveDocumentForDeleteOrRevoke(document);

            // Get all document assignments for this document
            var documentAssignments = await _documentAssignmentRepository.GetListAsync(
                documentId: input.DocumentId
            );

            if (documentAssignments == null || documentAssignments.Count == 0)
            {
                _logger.LogWarning("No document assignments found for DocumentId={DocumentId}", input.DocumentId);
                return true;
            }

            // Get all unique receiver user IDs
            var receiverUserIds = documentAssignments
                .Select(da => da.ReceiverUserId)
                .Distinct()
                .ToList();

            _logger.LogInformation("Revoking document from {RecipientCount} recipients", receiverUserIds.Count);

            // Update all document assignments status to REVOKE
            foreach (var documentAssignment in documentAssignments)
            {
                documentAssignment.Status = DocumentAssignmentStatus.REVOKE.ToString();
                await _documentAssignmentRepository.UpdateAsync(documentAssignment);
            }

            // Create notification
            var notificationTitleKey = "DocumentRevoked";
            var notificationContentKey = $"DocumentRevokedMessage|{document.StorageNumber}|{document.Title}|{CurrentUser.UserName ?? L["System"]}";

            var notification = new Notification(
                GuidGenerator.Create(),
                notificationTitleKey,
                notificationContentKey,
                SourceType.DOCUMENT.ToString(),
                EventType.DOCUMENT_REVOKED.ToString(),
                RelatedType.DOCUMENT.ToString(),
                "NORMAL",
                document.Id.ToString()
            );

            notification.TenantId = CurrentTenant.Id;
            await _notificationRepository.InsertAsync(notification);

            // Create notification receivers for each user
            foreach (var receiverUserId in receiverUserIds)
            {
                var notificationReceiver = new NotificationReceiver(
                    GuidGenerator.Create(),
                    notification.Id,
                    receiverUserId,
                    false
                );
                notificationReceiver.TenantId = CurrentTenant.Id;
                await _notificationReceiverRepository.InsertAsync(notificationReceiver);

                // Create document history with Action = THU HOI
                await _documentHistoryManager.CreateAsync(
                    input.DocumentId,
                    currentUserId.Value,
                    receiverUserId,
                    "THU_HOI",
                    $"Revoked document {document.Title} by {CurrentUser.UserName ?? L["System"]}"
                );
            }

            // Publish event to RabbitMQ for real-time notification
            await _distributedEventBus.PublishAsync(
                new NotificationCreatedEto
                {
                    NotificationId = notification.Id,
                    ReceiverUserIds = receiverUserIds
                }
            );

            _logger.LogInformation("RevokeDocumentAsync completed successfully: DocumentId={DocumentId}, RevokedFrom={RecipientCount} users",
                input.DocumentId, receiverUserIds.Count.ToString());

            return true;
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Error in RevokeDocumentAsync: DocumentId={DocumentId}", input.DocumentId);
            throw;
        }
    }

    /// <summary>
    /// Update document status by DocumentStatusCode enum.
    /// Looks up MasterData by Code and Type = "TRANG_THAI_VB".
    /// </summary>
    private async Task UpdateDocumentStatusAsync(Guid documentId, DocumentStatusCode statusCode)
    {
        try
        {
            var document = await _documentRepository.GetAsync(documentId);
            var code = statusCode.GetCode();

            var statusList = await _masterDataRepository.GetListAsync(
                x => x.Code == code && x.Type == MasterDataType.Status.GetTypeValue());

            var status = statusList.FirstOrDefault();
            if (status == null)
            {
                _logger.LogWarning("MasterData with Code='{Code}' and Type='TRANG_THAI_VB' not found. Document status will not be updated.", code);
                return;
            }

            document.StatusId = status.Id;
            await _documentRepository.UpdateAsync(document);

            _logger.LogInformation("Document status updated to {Code}: DocumentId={DocumentId}, StatusId={StatusId}",
                code, documentId, status.Id);
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Error updating document status to {Code}: DocumentId={DocumentId}",
                statusCode.GetCode(), documentId);
            // Don't throw - we don't want to fail the parent operation if status update fails
        }
    }
