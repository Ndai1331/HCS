                    sourceType: null,
                    creatorId: null,
                    sentToMeIds);

                var dtos = ObjectMapper.Map<List<DocumentWithNavigationProperties>, List<DocumentWithNavigationPropertiesDto>>(documents);
                await PopulateSentToMeDisplayNamesAsync(dtos);

                var items = dtos.Select(d => new
                {
                    No = d.Document.No,
                    Title = d.Document.Title,
                    FromUser = d.FromUserDisplayName,
                    Department = d.DepartmentDisplayName,
                    CurrentStatus = d.Document.CurrentStatus,
                    CompletedTime = d.Document.CompletedTime,
                    StorageNumber = d.Document.StorageNumber,
                    IncommingDate = d.Document.IncommingDate,
                    Field = d.Field?.Name,
                    Unit = d.Unit?.Name,
                    Workflow = d.Workflow?.Name,
                    Status = d.Status?.Name,
                    Type = d.Type?.Name,
                    UrgencyLevel = d.UrgencyLevel?.Name,
                    SecrecyLevel = d.SecrecyLevel?.Name
                });

                var memoryStream = new MemoryStream();
                await memoryStream.SaveAsAsync(items);
                memoryStream.Seek(0, SeekOrigin.Begin);
                return new RemoteStreamContent(memoryStream, "Documents.xlsx", "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet");
            }
        }

        return await base.GetListAsExcelFileAsync(input);
    }

    /// <summary>
    /// Delete and revoke are only allowed for archive documents (SourceType = Archive, menu sourceType = 0).
    /// </summary>
    private void EnsureArchiveDocumentForDeleteOrRevoke(Document document)
    {
        if (document.SourceType != DocumentSourceType.Archive)
        {
            throw new UserFriendlyException(L["DeleteRevokeOnlyInArchiveView"]);
        }
    }

    [Authorize(HCPermissions.Documents.Delete)]
    public override async Task DeleteAsync(Guid id)
    {
        var document = await _documentRepository.GetAsync(id);
        EnsureArchiveDocumentForDeleteOrRevoke(document);
        await base.DeleteAsync(id);
    }

    [Authorize(HCPermissions.Documents.Delete)]
    public override async Task DeleteByIdsAsync(List<Guid> documentIds)
    {
        if (documentIds == null || documentIds.Count == 0)
        {
            return;
        }

        var distinctIds = documentIds.Distinct().ToList();
        var documents = await _documentRepository.GetListAsync(d => distinctIds.Contains(d.Id));
        if (documents.Count != distinctIds.Count)
        {
            throw new UserFriendlyException(L["DocumentNotFound"]);
        }

        foreach (var document in documents)
        {
            EnsureArchiveDocumentForDeleteOrRevoke(document);
        }

        await base.DeleteByIdsAsync(documentIds);
    }

