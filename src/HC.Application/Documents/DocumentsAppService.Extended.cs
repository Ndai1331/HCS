    /// <summary>
    /// Hide &quot;Submit for signing&quot; on parent rows when any workflow child has instance IN_PROGRESS or COMPLETED.
    /// Show again when only RETURNED, REJECTED, or CANCELLED (e.g. revoked / overdue cancel).
    /// </summary>
    private async Task ApplySubmitSigningButtonVisibilityAsync(IReadOnlyList<DocumentWithNavigationPropertiesDto>? items)
    {
        if (items == null || items.Count == 0)
        {
            return;
        }

        var parentIds = items
            .Where(i => i.Document.SourceType != DocumentSourceType.Workflow)
            .Select(i => i.Document.Id)
            .Distinct()
            .ToList();
        if (parentIds.Count == 0)
        {
            return;
        }

        var docQueryable = await _documentRepository.GetQueryableAsync();
        var instQueryable = await _documentWorkflowInstanceRepository.GetQueryableAsync();

        var childPairs = await AsyncExecuter.ToListAsync(
            docQueryable
                .Where(d => d.ParentDocumentId != null && parentIds.Contains(d.ParentDocumentId.Value))
                .Select(d => new { d.Id, ParentId = d.ParentDocumentId!.Value }));

        if (childPairs.Count == 0)
        {
            foreach (var item in items.Where(i => i.Document.SourceType != DocumentSourceType.Workflow))
            {
                item.HideSubmitForSigningButton = false;
            }

            return;
        }

        var childIds = childPairs.Select(x => x.Id).Distinct().ToList();

        var blockingChildIds = await AsyncExecuter.ToListAsync(
            instQueryable
                .Where(i => childIds.Contains(i.DocumentId) &&
                            (i.Status == nameof(DocumentWorkflowInstanceStatus.IN_PROGRESS) ||
                             i.Status == nameof(DocumentWorkflowInstanceStatus.COMPLETED)))
                .Select(i => i.DocumentId)
                .Distinct());

        var hideParentIds = childPairs
            .Where(p => blockingChildIds.Contains(p.Id))
            .Select(p => p.ParentId)
            .ToHashSet();

        foreach (var item in items.Where(i => i.Document.SourceType != DocumentSourceType.Workflow))
        {
            item.HideSubmitForSigningButton = hideParentIds.Contains(item.Document.Id);
        }
    }

    public override async Task<IRemoteStreamContent> GetListAsExcelFileAsync(DocumentExcelDownloadDto input)
    {
        if (input.SourceType == DocumentSourceType.SentToMe)
        {
            var currentUserId = CurrentUser.Id;
            if (currentUserId.HasValue)
            {
                var downloadToken = await _downloadTokenCache.GetAsync(input.DownloadToken);
                if (downloadToken == null || input.DownloadToken != downloadToken.Token)
                {
                    throw new AbpAuthorizationException("Invalid download token: " + input.DownloadToken);
                }

                var sentToMeIds = await GetSentToMeDocumentIdsAsync(currentUserId.Value);
                var documents = await _documentRepository.GetListWithNavigationPropertiesAsync(
                    input.FilterText,
                    input.No,
                    input.Title,
                    input.CurrentStatus,
                    input.CompletedTimeMin,
                    input.CompletedTimeMax,
                    input.StorageNumber,
                    input.IncommingDateMin,
                    input.IncommingDateMax,
                    input.FieldId,
                    input.UnitId,
                    input.WorkflowId,
                    input.StatusId,
                    input.TypeId,
                    input.UrgencyLevelId,
                    input.SecrecyLevelId,
                    sourceType: null,
                    creatorId: null,
                    sentToMeIds);

                var dtos = ObjectMapper.Map<List<DocumentWithNavigationProperties>, List<DocumentWithNavigationPropertiesDto>>(documents);
                await PopulateSentToMeDisplayNamesAsync(dtos);

                var items = dtos.Select(d => new
                {
                    No = d.Document.No,
                    Title = d.Document.Title,
                    FromUser = d.FromUserDisplayName,
                    Department = d.DepartmentDisplayName,
                    CurrentStatus = d.Document.CurrentStatus,
                    CompletedTime = d.Document.CompletedTime,
                    StorageNumber = d.Document.StorageNumber,
                    IncommingDate = d.Document.IncommingDate,
                    Field = d.Field?.Name,
                    Unit = d.Unit?.Name,
                    Workflow = d.Workflow?.Name,
                    Status = d.Status?.Name,
                    Type = d.Type?.Name,
                    UrgencyLevel = d.UrgencyLevel?.Name,
                    SecrecyLevel = d.SecrecyLevel?.Name
                });

                var memoryStream = new MemoryStream();
                await memoryStream.SaveAsAsync(items);
                memoryStream.Seek(0, SeekOrigin.Begin);
                return new RemoteStreamContent(memoryStream, "Documents.xlsx", "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet");
            }
        }

        return await base.GetListAsExcelFileAsync(input);
    }

    /// <summary>
    /// Delete and revoke are only allowed for archive documents (SourceType = Archive, menu sourceType = 0).
    /// </summary>
    private void EnsureArchiveDocumentForDeleteOrRevoke(Document document)
    {
        if (document.SourceType != DocumentSourceType.Archive)
        {
            throw new UserFriendlyException(L["DeleteRevokeOnlyInArchiveView"]);
        }
    }

    [Authorize(HCPermissions.Documents.Delete)]
    public override async Task DeleteAsync(Guid id)
    {
        var document = await _documentRepository.GetAsync(id);
        EnsureArchiveDocumentForDeleteOrRevoke(document);
        await base.DeleteAsync(id);
    }

    [Authorize(HCPermissions.Documents.Delete)]
